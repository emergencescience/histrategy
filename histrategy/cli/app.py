def _get_player_decision() -> str | None:
    """Get player's free-text strategic decision.

    Returns:
        None for exit, "__plan__" to re-enter Plan Mode,
        "__state__" to view state, or the decision string.
    """
    console.print()
    console.print("[bold cyan]你的战略决策：[/]")
    console.print("[dim](自由输入 — 如同真实军师一般下达命令)[/]")
    console.print("[dim]  'plan' 重开内政会议 | 'state' 查看天下状态 | 'exit' 退出[/]")
    try:
        decision = Prompt.ask("").strip()
        if decision.lower() in ("exit", "quit", "退出", "q"):
            return None
        if decision.lower() in ("state", "状态"):
            return "__state__"
        if decision.lower() == "plan":
            return "__plan__"
        if not decision:
            console.print("[yellow][系统] 决策不能为空，请输入您的战略方针。[/]")
            return "__prompt_again__"
        return decision
    except (EOFError, KeyboardInterrupt):
        return None


