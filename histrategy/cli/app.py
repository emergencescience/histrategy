def _game_loop(engine: GameEngine):
    """Main game loop with Plan/Command two-phase flow.

    Fully unified through GameEngine:
      Plan Mode  -> engine.get_plan_data()
      Player types free-text decision
      Command Mode -> engine.process_turn()
    """
    show_plan = True
    while True:
        # Check for elimination
        player = engine.world_state.get_player_faction()
        if not player or not player.is_active or player.strength <= 0:
            _display_game_over({
                "type": "defeat",
                "message": (
                    "# 势力覆灭\n\n"
                    "你的势力已经不复存在。\n"
                    "乱世之中，成王败寇。\n\n"
                    "感谢游玩《三國志略》。"
                ),
            })
            break

        # === PLAN MODE ===========================================
        if show_plan:
            if engine.llm:
                _display_llm_plan_mode(engine)
            else:
                _display_offline_plan_mode(engine)
        show_plan = True  # reset for next loop iteration

        # === PLAYER DECISION =====================================
        console.print()
        decision = _get_player_decision()

        if decision is None:
            break
        if decision == "__plan__":
            continue
        if decision == "__state__":
            _display_state(engine)
            show_plan = False
            continue
        if decision == "__prompt_again__":
            show_plan = False
            continue

        # === COMMAND MODE ========================================
        with console.status("[yellow]天机运转，推演天下大势...[/]", spinner="dots"):
            result = engine.process_turn(decision)
            if engine.llm:
                _display_llm_command_result(result, engine.llm)
            else:
                _display_offline_command_result(engine, result)

            game_over = result.get("game_over")
            if game_over:
                _display_game_over(game_over)
                break


# ─── LLM Plan Mode Display ──────────────────────────────────

def _display_llm_plan_mode(engine: GameEngine):
    """Display LLM-generated Plan Mode: advisor court + suggestions in a single unified panel."""
    with console.status("[yellow]谋臣正在商议国策...[/]", spinner="dots"):
        plan = engine.get_plan_data()

    # Season summary
    summary = plan.get("season_summary", "")
    if summary:
        console.print()
        console.print(Align(
            Text(summary, style="italic bright_cyan"),
            align="center",
        ))

    # Construct unified Markdown text
    court_dialogue = plan.get("court_dialogue", "")
    suggestions = plan.get("suggestions", [])

    court_md = []
    if court_dialogue:
        court_md.append(court_dialogue.strip())
        court_md.append("")

    if suggestions:
        court_md.append("### 🎯 廷议决策方向参考")
        for i, s in enumerate(suggestions, 1):
            if s.startswith("【") and "】" in s:
                parts = s.split("】", 1)
                title = parts[0][1:]
                desc = parts[1].strip()
                court_md.append(f"{i}. **{title}** — {desc}")
            elif s.startswith("[") and "]" in s:
                parts = s.split("]", 1)
                title = parts[0][1:]
                desc = parts[1].strip()
                court_md.append(f"{i}. **{title}** — {desc}")
            else:
                court_md.append(f"{i}. {s}")
        court_md.append("")

    if court_md:
        console.print()
        console.print(Panel(
            Markdown("\n".join(court_md)),
            border_style="bright_magenta",
            title="🏛️ 议事厅 - 谋臣献策",
            title_align="left",
            padding=(1, 2),
        ))

    _print_llm_stats(engine.llm)


# ─── LLM Command Mode Display ───────────────────────────────

def _display_llm_command_result(result: dict, llm: LLMAdapter | None = None):
    """Display LLM Command Mode results as a single unified historical chronicle."""
    bureaucracy = result.get("bureaucracy", [])
    aftermath = result.get("aftermath", "")
    seeds = result.get("seeds", [])
    npc_reactions = result.get("npc_reactions", [])

    chronicle_md = []

    if aftermath:
        chronicle_md.append(aftermath.strip())
        chronicle_md.append("")

    if bureaucracy:
        chronicle_md.append("### 🏛️ 各司政务")
        for dept in bureaucracy:
            dept_name = dept.get("department", "")
            official = dept.get("official", "")
            action = dept.get("action", "")
            prefix = f"**[{dept_name}" + (f" · {official}" if official else "") + "]**"
            chronicle_md.append(f"- {prefix} {action}")
        chronicle_md.append("")

    if npc_reactions:
        chronicle_md.append("### ⚔️ 列国战志")
        for r in npc_reactions:
            chronicle_md.append(f"- {r}")
        chronicle_md.append("")

    if seeds:
        chronicle_md.append("### 🔮 伏线机锋")
        for s in seeds:
            trigger = s.get("trigger_after", "?")
            title = s.get("title", "未知")
            desc = s.get("description", "")
            chronicle_md.append(f"- **{title}** *({trigger}回合后)*: {desc}")
        chronicle_md.append("")

    if chronicle_md:
        console.print()
        console.print(Panel(
            Markdown("\n".join(chronicle_md)),
            border_style="bright_yellow",
            title="📜 局势推演纪事",
            title_align="left",
            padding=(1, 2),
        ))

    _print_llm_stats(llm)


def _print_llm_stats(llm: LLMAdapter | None):
    """Print LLM call performance and token stats."""
    if not llm or not getattr(llm, "last_call_stats", None):
        return
    stats = llm.last_call_stats
    latency = stats.get("latency", 0)
    pt = stats.get("prompt_tokens", 0)
    ct = stats.get("completion_tokens", 0)
    tt = stats.get("total_tokens", 0)
    rt = stats.get("reasoning_tokens", 0)

    msg = f"[dim]⚡ AI推演用时: {latency:.2f}s | Token: 输入 {pt}, 输出 {ct}, 共 {tt}[/]"
    if rt > 0:
        msg += f" [dim](含思维 {rt})[/]"

    console.print(Align(msg, align="right"))


